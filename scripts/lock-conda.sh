#!/usr/bin/env bash
# Regenerate the explicit conda lockfiles in conda/ from conda/environment.yml for
# Apple Silicon macOS and Linux x86_64/aarch64 (Linux also covers Windows via WSL).
# Users then create the environment with:
#   conda create -n Renv --file conda/renv-<platform>.txt
# Each platform is solved with conda's own solver for that platform, assuming
# macOS 14+ or glibc 2.35+ (Ubuntu 22.04+, the WSL default). No packages are
# downloaded. Safe to re-run; only rewrites conda/renv-*.txt.
set -euo pipefail

MINIFORGE_IMAGE="condaforge/miniforge3:26.9.4-0"
here="$(cd "$(dirname "$0")/.." && pwd)"

lock() {
  local subdir="$1" out="$2"
  docker run --rm -i -e CONDA_SUBDIR="$subdir" -e CONDA_OVERRIDE_OSX=14.0 \
    -e CONDA_OVERRIDE_GLIBC=2.35 -v "$here/conda":/w -w /w "$MINIFORGE_IMAGE" \
    python - "$subdir" > "$here/conda/$out.tmp" <<'PY'
import json, subprocess, sys
from ruamel.yaml import YAML
from conda.api import SubdirData
from conda.models.match_spec import MatchSpec

subdir = sys.argv[1]
env = YAML(typ="safe").load(open("environment.yml"))
channels = env["channels"]
specs = [s for s in env["dependencies"] if isinstance(s, str)]
solve = json.loads(subprocess.run(
    ["conda", "create", "--dry-run", "--json", "--override-channels", "-n", "lock"]
    + [a for c in channels for a in ("-c", c)] + specs,
    check=True, capture_output=True, text=True).stdout)

lines = [
    "# Explicit lockfile generated by scripts/lock-conda.sh from conda/environment.yml.",
    "# Create the environment with: conda create -n Renv --file <this file>",
    f"# platform: {subdir}",
    "@EXPLICIT",
]
for link in sorted(solve["actions"]["LINK"], key=lambda l: l["name"]):
    spec = MatchSpec(f'{link["channel"]}/{link["platform"]}::{link["name"]}'
                     f'=={link["version"]}={link["build_string"]}')
    found = SubdirData.query_all(spec, channels=channels, subdirs=[link["platform"]])
    if not found:
        sys.exit(f"no repodata record for {spec}")
    rec = found[0]
    lines.append(f"{rec.url}#{rec.md5}")
print("\n".join(lines))
PY
  local n
  n=$(grep -c '^https' "$here/conda/$out.tmp" || true)
  if [ "$n" -eq 0 ]; then
    echo "error: no packages resolved for $subdir" >&2
    rm -f "$here/conda/$out.tmp"
    exit 1
  fi
  mv "$here/conda/$out.tmp" "$here/conda/$out"
  echo "wrote conda/$out ($n packages)"
}

# Linux files are named after `uname -m`, so instructions can use renv-linux-$(uname -m).txt
lock osx-arm64 renv-osx-arm64.txt
lock linux-64 renv-linux-x86_64.txt
lock linux-aarch64 renv-linux-aarch64.txt
